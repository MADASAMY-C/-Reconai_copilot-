"""Weekly digest: deterministic facts -> (Claude | rule-based) narrative -> HTML -> email.

Run:  python -m reconai.digest --days 7 [--send]
"""
from __future__ import annotations

import argparse
import html
import json
import os
import pathlib
import smtplib
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText

import pandas as pd

from . import ai_agent, db, failures, metrics, recon


def build_facts(f: dict, days: int = 7) -> dict:
    end = f["payments"].created_at.max().normalize()
    start = end - pd.Timedelta(days=days - 1)
    cur = metrics.kpis(f, start, end)
    prev = metrics.kpis(f, start - pd.Timedelta(days=days), start - pd.Timedelta(days=1))
    p = failures.prepare(metrics.slice_window(f["payments"], "created_at", start, end))
    hs = failures.hotspots(p, top=4)
    mm = recon.reconcile(f)
    return {
        "period": {"start": str(start.date()), "end": str(end.date()), "days": days},
        "kpis": cur, "previous_kpis": prev,
        "success_rate_change_pp": round((cur["success_rate"] - prev["success_rate"]) * 100, 2),
        "failure_hotspots": json.loads(hs.to_json(orient="records")),
        "reconciliation": {
            "open_issues": int(len(mm)), "total_at_risk_inr": round(float(mm.amount_at_risk_inr.sum()), 2),
            "new_this_period": int((mm.date >= start).sum()),
            "by_type": json.loads(recon.summarize(mm).to_json(orient="records")),
            "largest": json.loads(mm.head(5).to_json(orient="records", date_format="iso")),
        },
    }


def rule_based_narrative(facts: dict) -> dict:
    k, rc = facts["kpis"], facts["reconciliation"]
    delta = facts["success_rate_change_pp"]
    actions = []
    for row in rc["by_type"][:2]:
        actions.append({"title": recon.CHECK_LABELS[row["check"]], "why": recon.CHECK_ACTIONS[row["check"]],
                        "value_at_stake_inr": abs(row["amount_at_risk_inr"]),
                        "priority": "high" if abs(row["amount_at_risk_inr"]) >= 5000 else "medium"})
    if facts["failure_hotspots"]:
        h = facts["failure_hotspots"][0]
        actions.append({"title": f"Investigate failures: {h['segment']}",
                        "why": f"{h['failure_rate']:.0%} fail vs {h['baseline_rate']:.0%} baseline; top reason: {h['top_error']}.",
                        "value_at_stake_inr": h["failed_value_inr"], "priority": "medium"})
    return {
        "headline": f"{k['success_rate']:.1%} payment success ({delta:+.1f} pp); ₹{rc['total_at_risk_inr']:,.0f} flagged in reconciliation.",
        "summary": (f"You processed ₹{k['gmv_inr']:,.0f} across {k['successful']:,} successful payments "
                    f"({k['attempts']:,} attempts). ₹{k['failed_value_inr']:,.0f} of attempted value failed. "
                    f"{rc['open_issues']} reconciliation issues are open ({rc['new_this_period']} new this period)."),
        "top_actions": actions[:3], "watchlist": [],
    }


def make_narrative(facts: dict) -> tuple[dict, str]:
    if ai_agent.available():
        try:
            return ai_agent.digest_narrative(facts), "qwen"
        except Exception as ex:  # never fail the weekly send because the LLM is down
            print("Qwen unavailable, using rule-based digest:", ex)
    return rule_based_narrative(facts), "rules"


def render_html(facts: dict, nar: dict) -> str:
    def esc(x):
        return html.escape("" if x is None else str(x))
    e, k = esc, facts["kpis"]
    acts = "".join(
        f"<li style='margin-bottom:10px'><b>{e(a.get('title', ''))}</b> "
        f"<span style='color:#b45309'>[{e(a.get('priority', ''))} · ₹{float(a.get('value_at_stake_inr') or 0):,.0f}]</span><br>{e(a.get('why', ''))}</li>"
        for a in nar.get("top_actions", []))
    watch = "".join(f"<li>{e(w)}</li>" for w in nar.get("watchlist", []))
    tiles = "".join(f"<td style='padding:8px 14px;border:1px solid #e5e7eb;text-align:center'><div style='font-size:12px;color:#6b7280'>{e(l)}</div>"
                    f"<div style='font-size:18px;font-weight:600'>{e(v)}</div></td>" for l, v in [
                        ("GMV", f"₹{k['gmv_inr']:,.0f}"), ("Success rate", f"{k['success_rate']:.1%}"),
                        ("Failed value", f"₹{k['failed_value_inr']:,.0f}"), ("Flagged ₹", f"₹{facts['reconciliation']['total_at_risk_inr']:,.0f}")])
    p = facts["period"]
    return (f"<div style='font-family:Arial,sans-serif;max-width:640px;margin:auto;color:#111827'>"
            f"<h2 style='margin-bottom:4px'>{e(nar['headline'])}</h2>"
            f"<div style='color:#6b7280;font-size:13px'>Weekly payments digest · {p['start']} → {p['end']}</div>"
            f"<p>{e(nar['summary'])}</p><table style='border-collapse:collapse;margin:12px 0'><tr>{tiles}</tr></table>"
            f"<h3>Do these first</h3><ol>{acts}</ol>"
            + (f"<h3>Watchlist</h3><ul>{watch}</ul>" if watch else "") +
            "<div style='color:#9ca3af;font-size:12px;margin-top:20px'>Generated by ReconAI.</div></div>")


def send_email(subject: str, body_html: str) -> bool:
    host, to = os.getenv("SMTP_HOST"), os.getenv("DIGEST_TO")
    if not (host and to):
        return False
    user, pwd = os.getenv("SMTP_USER", ""), os.getenv("SMTP_PASSWORD", "")
    msg = MIMEMultipart("alternative")
    msg["Subject"], msg["From"], msg["To"] = subject, os.getenv("DIGEST_FROM", user or "reconai@localhost"), to
    msg.attach(MIMEText(body_html, "html"))
    try:
        with smtplib.SMTP(host, int(os.getenv("SMTP_PORT", "587"))) as s:
            s.starttls()
            if user:
                s.login(user, pwd)
            s.sendmail(msg["From"], [t.strip() for t in to.split(",")], msg.as_string())
    except Exception:  # optional email must never break the product
        return False
    return True


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--days", type=int, default=7)
    ap.add_argument("--send", action="store_true")
    ap.add_argument("--out", default="out")
    a = ap.parse_args()
    from . import seed
    seed.ensure_demo_data()
    facts = build_facts(db.read_all(), a.days)
    nar, source = make_narrative(facts)
    body = render_html(facts, nar)
    path = pathlib.Path(a.out) / f"digest_{facts['period']['end']}.html"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body, encoding="utf-8")
    db.log_event("cron", "digest_generated", f"source={source}")
    print(f"Digest ({source}) written to {path}")
    if a.send:
        print("Email sent." if send_email(nar["headline"], body) else "SMTP not configured; skipped sending.")


if __name__ == "__main__":
    main()
